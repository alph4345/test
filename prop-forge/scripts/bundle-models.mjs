// Bundles the creator-supplied reference models into the app as templates.
//
//   node scripts/bundle-models.mjs <buster_sword_complete.stl> <gunblade files dir>
//
// Each mesh is repaired, moved into the template frame (Y along the weapon,
// blade starting at y = 0, X across the width, Z through the thickness,
// millimetres), lightly simplified (< 0.03 mm deviation), gzipped and
// written to src/templates/bundled-models.js.
import fs from 'fs';
import path from 'path';
import zlib from 'zlib';
import { initManifold } from '../src/engine/manifold.js';
import { parseSTLRaw, repairMesh } from '../src/ui/stlimport.js';

const [busterFile, gunDir] = process.argv.slice(2);
if (!busterFile || !gunDir) { console.error('usage: node scripts/bundle-models.mjs <buster_sword_complete.stl> <gunblade dir>'); process.exit(1); }

const M = await initManifold();

function load(file) {
  const buf = fs.readFileSync(file);
  return repairMesh(parseSTLRaw(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))).mesh;
}

// map: (x, y, z) in the file -> template frame
function solid(mesh, map) {
  const v = new Float32Array(mesh.verts.length);
  for (let i = 0; i < v.length; i += 3) {
    const p = map(mesh.verts[i], mesh.verts[i + 1], mesh.verts[i + 2]);
    v[i] = p[0]; v[i + 1] = p[1]; v[i + 2] = p[2];
  }
  const mm = new M.Mesh({ numProp: 3, vertProperties: v, triVerts: mesh.tris });
  mm.merge();
  let m = new M.Manifold(mm);
  if (m.volume() < 0) throw new Error('inside-out mesh');
  // overlapping shells (e.g. grips modelled on top of a handle) are merged
  let comps = m.decompose().filter((c) => c.volume() > 0);
  if (comps.length > 1) m = M.Manifold.union(comps);
  // shells that only touch (e.g. a grip modelled as two halves) stay
  // separate after a union; grow each by 0.05 mm so they fuse
  comps = m.decompose().filter((c) => c.volume() > 0);
  if (comps.length > 1) {
    m = M.Manifold.union(comps.map((c) => {
      const b = c.boundingBox();
      const ctr = [0, 1, 2].map((k) => (b.min[k] + b.max[k]) / 2);
      const k = [0, 1, 2].map((i) => 1 + 0.1 / Math.max(1, b.max[i] - b.min[i]));
      return c.translate(ctr.map((v) => -v)).scale(k).translate(ctr);
    }));
  }
  return m.simplify(0.03);
}

function bboxOfRaw(mesh) {
  const min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < mesh.verts.length; i++) { const k = i % 3; min[k] = Math.min(min[k], mesh.verts[i]); max[k] = Math.max(max[k], mesh.verts[i]); }
  return { min, max };
}

const out = {};
const thumbs = {};
function pack(key, m) {
  const g = m.getMesh();
  const verts = new Float32Array(g.numProp === 3 ? g.vertProperties : g.vertProperties.filter((_, i) => i % g.numProp < 3));
  const tris = new Uint32Array(g.triVerts);
  const raw = Buffer.concat([Buffer.from(new Uint32Array([verts.length, tris.length]).buffer), Buffer.from(verts.buffer), Buffer.from(tris.buffer)]);
  out[key] = zlib.gzipSync(raw, { level: 9 }).toString('base64');
  const polys = m.project().simplify(0.6).toPolygons().map((p) => p.map(([x, y]) => [Math.round(x), Math.round(y)]));
  thumbs[key] = polys;
  console.log(key.padEnd(18), `${tris.length / 3} tris`, `vol ${(m.volume() / 1000).toFixed(0)} cm³`, `${(out[key].length / 1024).toFixed(0)} KB`);
}

// Buster Sword (file units: cm). Blade base -> y = 0, blade centred.
const b = load(busterFile);
pack('buster', solid(b, (x, y, z) => [x * 10 - 151.5, y * 10 + 337, z * 10 + 28.55]));

// Revolver gunblade parts, assembled. File axes: X thickness, Y length
// (blade towards -Y), Z width. Offsets line the parts up end to end.
const parts = { blade: [-169, -3], blade_tip: [-399, 15], frame: [0, 0], handle: [90, 5] }; // grip seated 4 mm into the frame
for (const [name, [dy, dz]] of Object.entries(parts)) {
  const mesh = load(path.join(gunDir, `gb_${name}.stl`));
  const bb = bboxOfRaw(mesh);
  const xc = (bb.min[0] + bb.max[0]) / 2;
  pack(`gunblade_${name}`, solid(mesh, (x, y, z) => [z + dz - 40, -(y + dy), x - xc]));
}

const header = `// Generated by scripts/bundle-models.mjs. Do not edit.
// Buster Sword model by Budward (thingiverse.com/thing:1794243) and Revolver
// gunblade model by Chemvaldes (thingiverse.com/thing:3825730), bundled with
// the creator's permission.
`;
fs.writeFileSync(new URL('../src/templates/bundled-models.js', import.meta.url),
  `${header}export const MODELS = ${JSON.stringify(out, null, 1)};\nexport const THUMBS = ${JSON.stringify(thumbs)};\n`);
console.log('written src/templates/bundled-models.js');
